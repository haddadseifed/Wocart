// @vitest-environment node
/**
 * The theme's manifest as a build file: an editor and a release read
 * `/wocart-theme.json` instead of running the theme, so it must be
 * prerendered, served at the SDK's path, and a manifest that validates — the
 * whole catalog, settings, text packs, the home surface with its default
 * document, and that the theme serves an editor's preview.
 */
import { describe, expect, it } from "vitest";
import { THEME_MANIFEST_PATH, THEME_PREVIEW_PATH, THEME_SDK_VERSION, validateThemeManifest } from "@wocart/theme";
import * as endpoint from "@/pages/wocart-theme.json";
import * as previewPage from "@/pages/wocart-preview.astro";
import { theme00 } from "@/theme/theme";
import shippedHome from "@/theme/pages/home.page.json";
import shippedProduct from "@/theme/pages/product.page.json";
import { ar } from "@/theme/content/ar";
import { en } from "@/theme/content/en";
import { fr } from "@/theme/content/fr";

describe("the manifest file", () => {
  it("is prerendered at the SDK's manifest path", () => {
    expect(endpoint.prerender).toBe(true);
    expect(THEME_MANIFEST_PATH).toBe("/wocart-theme.json");
  });

  it("serves a manifest that validates, generated by the SDK the theme ships", async () => {
    const response = endpoint.GET();
    expect(response.headers.get("Content-Type")).toBe("application/json; charset=utf-8");
    const checked = validateThemeManifest(await response.json());
    expect(checked.issues).toEqual([]);
    const manifest = checked.manifest!;
    expect(manifest.key).toBe("theme-00");
    expect(manifest.version).toBe(theme00.version);
    expect(manifest.sdkVersion).toBe(THEME_SDK_VERSION);
    expect(Object.keys(manifest.components).sort()).toEqual(Object.keys(theme00.components).sort());
  });

  it("carries every surface, the home and product pages with their default documents, and every text pack", async () => {
    const manifest = (await endpoint.GET().json()) as Awaited<ReturnType<typeof validateThemeManifest>>["manifest"] & object;
    expect(manifest.surfaces.map((surface) => surface.key)).toEqual(["home", "product", "collection", "category", "catalog", "page", "thank-you", "landing", "search", "track-order", "checkout", "contact"]);
    expect(manifest.surfaces[0]).toEqual({ key: "home", label: theme00.surfaces[0].label, pageType: "home", document: shippedHome });
    expect(manifest.surfaces[1]).toMatchObject({ key: "product", pageType: "product", document: shippedProduct, required: [{ type: "product-main", min: 1, max: 1 }] });
    expect(manifest.content).toEqual({ ar: { ...ar }, fr: { ...fr }, en: { ...en } });
  });

  it("says the theme serves a preview, at the route it renders on demand", async () => {
    const manifest = (await endpoint.GET().json()) as { preview: boolean };
    expect(manifest.preview).toBe(true);
    expect(THEME_PREVIEW_PATH).toBe("/wocart-preview");
    expect((previewPage as { prerender?: boolean }).prerender).toBe(false);
  });
});
