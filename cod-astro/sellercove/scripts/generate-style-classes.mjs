#!/usr/bin/env node
// Writes the style classes the theme's sizes allow (`@wocart/theme`'s
// `themeStyleSheet`) into the theme's stylesheet, so they ship inlined with
// the rest of its CSS instead of as a second request. Run after changing
// src/theme/style-sizes.json; a test fails while the file is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { themeStyleSheet } from "@wocart/theme";

const sizes = JSON.parse(readFileSync(new URL("../src/theme/style-sizes.json", import.meta.url), "utf8"));
const header = "/* Generated by scripts/generate-style-classes.mjs from src/theme/style-sizes.json — do not edit. */\n";
writeFileSync(new URL("../src/theme/styles/style-classes.css", import.meta.url), `${header}${themeStyleSheet(sizes).replaceAll("}", "}\n")}`);
